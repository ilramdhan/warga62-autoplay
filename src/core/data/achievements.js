/** Cocokkan satu teks tugas mingguan. @returns {{text, count, flags, role, roomPreset} | null} */
export function matchWeeklyTask(text) {
  const s = String(text ?? '');
  const hit = WEEKLY_TASK_PATTERNS.find((p) => p.re.test(s));
  if (!hit) return null;
  const n = s.match(/(\d+)/);
  return {
    text: s,
    count: n ? Number(n[1]) : 1,
    flags: { ...hit.flags },
    role: hit.role ?? 'all',
    roomPreset: hit.roomPreset ? { ...hit.roomPreset } : undefined,
  };
}

